package plymeld.commands

import io.kotest.core.spec.style.StringSpec
import io.kotest.matchers.shouldBe
import io.kotest.matchers.string.shouldContain
import io.kotest.matchers.string.shouldNotContain
import java.nio.file.Files

/**
 * `plymeld printer send` refuses a file with a number a printer's firmware may refuse or act wrongly on (BadNumbers), before
 * it reads the config or reaches a printer: the last gate, for a file of any origin (an older build's dead feed, a hand
 * edit). No printer is involved: the test's home has none configured, so a file that passes the scan is refused after it
 * for that (the control: it got past the scan).
 */
class SendNumbersTest : StringSpec({
    fun send(gcode: String): Pair<Int, String> {
        val f = Files.createTempDirectory("plymeld-send").resolve("part.gcode").also { Files.writeString(it, gcode) }
        val said = StringBuilder()
        val code = Commands.invoke(listOf("printer", "send", f.toString()), { said.appendLine(it) })
        return code to said.toString()
    }
    val good = "; generated by a test\nM83\nG28\nM109 S210\nG1 X10 Y10 Z0.2 F6000\nG1 X20 Y10 E0.5 F1500\nM104 S0\n"

    "a file with a dead feed, a NaN, or a negative temperature is not sent, naming each line; control: the same file with good numbers gets past the scan" {
        val (code, said) = send(good.replace("G1 X20 Y10 E0.5 F1500", "G1 F0\nG1 X20 Y10 E0.5").replace("M109 S210", "M109 S-210") + "SET_VELOCITY_LIMIT ACCEL=NaN\n")
        println(said)
        (code != 0) shouldBe true
        said shouldContain "is not sent: 3 line(s) hold a number a printer may refuse or act wrongly on"
        said shouldContain "line 4: 'M109 S-210': a temperature of -210 °C, below 0"
        said shouldContain "line 6: 'G1 F0': a move at feed rate F0, no speed"
        said shouldContain "line 9: 'SET_VELOCITY_LIMIT ACCEL=NaN'"
        val (code2, said2) = send(good)
        println(said2)
        (code2 != 0) shouldBe true                     // no printer in the test's home
        said2 shouldNotContain "is not sent"
    }

    "a NaN in a comment alone does not stop a send (a firmware ignores comments); the source block is not read" {
        val (_, said) = send(good + "; estimated printing time = NaN s\n; PLYMELD_SOURCE_BLOCK_START\nG1 F0\n; PLYMELD_SOURCE_BLOCK_END\n")
        said shouldNotContain "is not sent"
    }
})
