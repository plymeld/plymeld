package plymeld.config

/**
 * The tables of the settings reference page, generated from [Schema] as [SchemaJson] is, so the page cannot drift
 * from what plymeld reads (the hand-kept rows had drifted: meanings reworded, rows under the wrong section, a
 * missing `<key>`). The page's own text stays above [MARKER]; everything below it is [tables]. `plymeld schema --markdown
 * FILE` rewrites it; a test holds the committed page to it.
 */
object SchemaMarkdown {
    const val MARKER = "<!-- generated by `plymeld schema --markdown`: everything below this line; do not edit by hand -->"

    /** Each path's section: `hardware.<kind>` for the hardware, else its first segment. */
    private fun section(d: Schema.Decl) = if (d.segments[0] == "hardware") "${d.segments[0]}.${d.segments[1]}" else d.segments[0]

    private fun cell(s: String) = s.replace("|", "\\|").replace("\n", " ")

    private fun meaning(d: Schema.Decl): String = when (val t = d.type) {
        is Schema.Type.Quantity -> "${d.meaning} — ${t.label}; or a formula (= ...)"
        is Schema.Type.Ref, is Schema.Type.Numbers, is Schema.Type.Point -> "${d.meaning} (${t.label})"
        else -> d.meaning
    }

    private fun value(t: Schema.Type): String = when (t) {
        is Schema.Type.Bool -> "`true` or `false`"
        is Schema.Type.Choice -> "one of " + t.options.joinToString { "`$it`" }
        is Schema.Type.Choices -> "a list of " + t.options.joinToString { "`$it`" }
        else -> "string"
    }

    /** Every declared path, by section in the schema's order, one table each. */
    fun tables(): String {
        val bySection = LinkedHashMap<String, MutableList<Schema.Decl>>()
        for (d in Schema.decls) bySection.getOrPut(section(d)) { ArrayList() } += d
        val out = StringBuilder()
        for ((s, decls) in bySection) {
            out.append("\n## `").append(s).append("`\n\n| path | meaning | value |\n|---|---|---|\n")
            for (d in decls) out.append("| `").append(d.path).append("` | ").append(cell(meaning(d))).append(" | ").append(value(d.type)).append(" |\n")
        }
        return out.toString()
    }

    /** [page] with everything after its [MARKER] line replaced by [tables]; refused when the page has no marker. */
    fun into(page: String): String {
        val at = page.indexOf(MARKER)
        require(at >= 0) { "the page has no marker line ($MARKER)" }
        return page.substring(0, at + MARKER.length) + "\n" + tables()
    }
}
