package plymeld.commands

import com.github.ajalt.clikt.core.UsageError
import com.github.ajalt.clikt.core.parse
import io.kotest.assertions.throwables.shouldThrow
import io.kotest.core.spec.style.StringSpec
import io.kotest.matchers.shouldBe
import io.kotest.matchers.string.shouldContain
import plymeld.config.Config
import plymeld.config.ConfigStack
import java.nio.file.Files
import java.nio.file.Path

/**
 * `plymeld calibrate first-layer values` on a copy of the repo's sample config: the window it writes, read back through
 * the whole config; a window there before replaced; undo; and the readings and plates it refuses. The plate is a
 * first-layer plate's g-code as plymeld writes it (its conditions block and its cells), 3 speeds x 2 heights, two columns,
 * one tile left out.
 */
class FirstLayerValuesTest : StringSpec({
    val samples = Path.of("..", "test-models", "config").toAbsolutePath().normalize()
    fun plate(leftOut1: String = ", melt limit 15 mm3/s, left out: tile 3.2 (140 mm/s, 0.24 mm: 16.0 mm3/s)", extraCell: String = "") = """
        ; HEADER_BLOCK_START
        ; generated by plymeld 0.0.1-test
        ; total layer number: 1
        ; CALIBRATION_PLATE_START
        ; plate = first-layer (one layer of first-layer tiles)
        ; filament = pla-white, tool 1, build plate textured-pei
        ; first_layer_tiles = speeds 60, 100, 140 mm/s (a group of rows each, front to back), heights 0.2, 0.24 mm (a row each in every group, front to back), 0.5 mm lines
        ; block 1 = 210 C, 13.5 mm3/s$leftOut1
        ; block 2 = 220 C, 13.5 mm3/s
        ; CALIBRATION_PLATE_END
    """.trimIndent() + "\n" + (1..2).flatMap { k -> (1..3).flatMap { r -> (1..2).mapNotNull { c ->
        if (k == 1 && r == 3 && c == 2) null else "; CELL: block $k tile $r.$c" } } }.joinToString("\n") + extraCell + "\n"
    fun copy(gcode: String = plate()): Path {
        val d = Files.createTempDirectory("plymeld-first-layer-values")
        Files.list(samples).use { s -> s.forEach { Files.copy(it, d.resolve(it.fileName)) } }
        Files.writeString(d.resolve("plate.gcode"), gcode)
        return d
    }
    fun run(dir: Path, vararg args: String) = FirstLayerValuesCommand().parse(listOf("-cf", dir.resolve("0*.toml").toString(), "--journal", dir.resolve("journal.json").toString(),
        "--plate-gcode", dir.resolve("plate.gcode").toString()) + args)
    fun window(dir: Path) = Config(ConfigStack.load(listOf(dir.resolve("0*.toml").toString()), emptyList()), emptyList()).firstLayerWindows["pla-white"]?.get("textured-pei")

    "the readings written as the filament's window on the plate's build plate, for the tool's bore; it reads back through the config" {
        val dir = copy()
        // control: the sample has no window
        window(dir) shouldBe null
        run(dir, "210=0.24,100", "220=0.2,140")
        val w = window(dir)!!
        w.boreMm shouldBe 0.4
        w.from!! shouldContain "plate.gcode, tool 1, build plate textured-pei"
        w.readings.map { Triple(it.tempC, it.heightMinMm, it.speedMaxMmS) } shouldBe listOf(Triple(210.0, 0.24, 100.0), Triple(220.0, 0.2, 140.0))
        Files.readString(dir.resolve("01_FILAMENTS.toml")) shouldContain "# Per column, the lowest good nozzle height (every lower one bad) and the fastest good speed."
    }

    "a column with no good tile is left out; a window there before is replaced whole; undo restores the file exactly" {
        val dir = copy(); val f = dir.resolve("01_FILAMENTS.toml"); val original = Files.readString(f)
        run(dir, "210=0.24,100", "220=0.2,140")
        run(dir, "210=none", "220=0.24,60")
        window(dir)!!.readings.map { Triple(it.tempC, it.heightMinMm, it.speedMaxMmS) } shouldBe listOf(Triple(220.0, 0.24, 60.0))
        Files.readString(f) shouldContain "no good tile at 210 C, left out"
        val j = Journal.read(dir.resolve("journal.json"))
        j.undo(); Journal.read(dir.resolve("journal.json")).undo()
        Files.readString(f) shouldBe original
    }

    "refused: a column missing or not on the plate, a height or speed the plate did not try, a tile it left out, a plate in disagreement" {
        val dir = copy(); val f = dir.resolve("01_FILAMENTS.toml"); val original = Files.readString(f)
        shouldThrow<UsageError> { run(dir, "210=0.24,100") }.message!! shouldContain "220 C missing"
        shouldThrow<UsageError> { run(dir, "210=0.24,100", "220=0.2,140", "230=0.2,60") }.message!! shouldContain "230 C is not one of the plate's columns"
        shouldThrow<UsageError> { run(dir, "210=0.28,100", "220=0.2,140") }.message!! shouldContain "0.28 mm is not one of the plate's heights"
        shouldThrow<UsageError> { run(dir, "210=0.24,120", "220=0.2,140") }.message!! shouldContain "120 mm/s is not one of the plate's speeds"
        shouldThrow<UsageError> { run(dir, "210=0.24,140", "220=0.2,140") }.message!! shouldContain "the plate left out its 140 mm/s tile at 0.24 mm"
        shouldThrow<UsageError> { run(dir, "210=none", "220=none") }.message!! shouldContain "no column has a good tile"
        shouldThrow<UsageError> { run(dir, "210=0.24", "220=0.2,140") }.message!! shouldContain "a reading is TEMP=HEIGHT,SPEED"
        Files.readString(f) shouldBe original
        // the plate's conditions and its tiles must agree: a left-out tile off the plate; one that was printed; one neither
        fun refused(gcode: String) = shouldThrow<UsageError> { run(copy(gcode), "210=0.2,60", "220=0.2,60") }.message!!
        refused(plate(", left out: tile 3.2 (x); tile 8.1 (y)")) shouldContain "tile 8.1 as left out; the plate has 3 speeds x 2 heights"
        refused(plate(", left out: tile 3.2 (x)", "\n; CELL: block 1 tile 3.2")) shouldContain "tile 3.2 of column 1 is printed, but its conditions list it as left out"
        refused(plate("")) shouldContain "tile 3.2 of column 1 is neither printed nor listed as left out"
    }
})
