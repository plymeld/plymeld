package plymeld.check

import io.kotest.core.spec.style.StringSpec
import io.kotest.matchers.shouldBe
import io.kotest.matchers.string.shouldContain
import io.kotest.matchers.string.shouldStartWith
import plymeld.core.FlashStudioHeader
import plymeld.core.Predict

/**
 * The Creator 5 file header (Flash Studio's layout) and the tool-change count it reports: a T before
 * anything is extruded selects the starting tool, it is not a change.
 */
class MachineHeaderTest : StringSpec({
    val body = "; generated by plymeld test\n; total layer number: 2\nT1\nG1 X1 Y0 E5\n;LAYER_CHANGE\n;Z:0.2\nG1 X10 Y0 E2.5\nG1 E-0.8\nT2\nG1 E0.8\nG1 X20 Y0 E1\n;LAYER_CHANGE\n;Z:0.4\nG1 X30 Y0 E1\n"

    "Flash Studio's duration format" {
        FlashStudioHeader.hms(65998.0) shouldBe "18h 19m 58s"
        FlashStudioHeader.hms(372.0) shouldBe "6m 12s"
        FlashStudioHeader.hms(9.0) shouldBe "9s"
    }

    "filament per tool follows the T commands, retractions netted out" {
        FlashStudioHeader.filamentByTool(body, 4).toList() shouldBe listOf(0.0, 6.7, 2.8, 0.0)
    }

    "a T before any extrusion selects the starting tool; a later one is a change" {
        Predict.toolChanges(body) shouldBe 1
        Predict.toolChanges("G1 X1 Y0 E1\nT1\nG1 X2 Y0 E1\n") shouldBe 1        // control: no selection first, from tool 0
    }

    "the header replaces the writer's first lines and carries the prediction" {
        val out = FlashStudioHeader.prepend(body, "test", listOf(FlashStudioHeader.Tool("PLA", "#FFFFFF"), FlashStudioHeader.Tool(null, null), FlashStudioHeader.Tool(null, null)), 1.75,
            Predict.Prediction(372.0, 9.5, "test", listOf(9.0)))
        out shouldStartWith "; HEADER_BLOCK_START\n"
        out shouldContain "; total layer number: 2\n"
        out shouldContain "; max_z_height: 0.4\n"
        out shouldContain "; <filament id=\"1\" type=\"PLA\" color=\"#FFFFFF\" used_m=\"0.00\" />"
        out shouldContain "; estimated printing time (normal mode) = 6m 12s\n"
        out shouldContain "; estimated first layer printing time (normal mode) = 9s\n"
        out.lines().count { it.startsWith("; generated by") } shouldBe 1
    }

    "the generator line carries no date, so the same inputs give the same file (docs/gcode-format.md)" {
        fun header() = FlashStudioHeader.prepend(body, "9.9.9", listOf(FlashStudioHeader.Tool("PLA", null)), 1.75, Predict.Prediction(372.0, 9.5, "test", listOf(9.0)))
        val versionLine = Regex("""^; generated by plymeld (\S+)$""")
        header().lines().take(10).firstNotNullOfOrNull { versionLine.find(it) }?.groupValues?.get(1) shouldBe "9.9.9"
        header() shouldBe header()
        // control: the line with a date, as it was written before, does not match the format's version line
        versionLine.find("; generated by plymeld 9.9.9 on 2026-11-01 at 21:30:32") shouldBe null
    }
})
