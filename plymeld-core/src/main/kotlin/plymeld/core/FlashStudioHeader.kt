package plymeld.core

import java.util.Locale

/**
 * The header Flash Studio puts at the top of its Creator 5 g-code, which the printer may read for its
 * screen (time, filament per tool): the `HEADER_BLOCK` (generator, layers, filament diameter, height,
 * tools), filament used per tool, one `<filament .../>` line per tool, filament changes, layer count, and
 * the estimated times. Layout as observed in Flash Studio 1.7.18's output; which lines the printer
 * actually reads is not known. Left out: grams (not written yet, though a filament's density is a setting),
 * cost (plymeld has no price yet) and
 * Flash Studio's `tray_info_idx` (its filament-library id; meaning to the printer not known).
 */
object FlashStudioHeader {
    /** One filament of the loadout (by number: the tools' indexes, then the slots swapped in by hand): its kind (PLA ...) and color (#RRGGBB), when known. */
    class Tool(val kind: String?, val color: String?)

    /**
     * [body] with the header in place of the writer's own first lines ("; generated by", "; total layer
     * number"). [tools]: every filament of the loadout by number (1..n: every tool of the machine in order, then the slots
     * swapped in by hand on a tool). [prediction]: plymeld's for this body. The generator line carries no date or time,
     * so the same inputs give the same file (docs/gcode-format.md).
     */
    fun prepend(body: String, version: String, tools: List<Tool>, diameterMm: Double, prediction: Predict.Prediction): String {
        val lines = body.lines()
        val layers = lines.count { it.startsWith(";LAYER_CHANGE") || it.startsWith("; CHANGE_LAYER") }
        val maxZ = lines.mapNotNull { l -> when { l.startsWith(";Z:") -> l.removePrefix(";Z:"); l.startsWith("; Z_HEIGHT:") -> l.removePrefix("; Z_HEIGHT:"); else -> null }?.trim()?.toDoubleOrNull() }.maxOrNull() ?: 0.0
        val mm = filamentByTool(body, tools.size)
        val area = Math.PI * diameterMm * diameterMm / 4
        fun list(v: List<String>) = v.joinToString(", ")
        val h = StringBuilder()
        h.append("; HEADER_BLOCK_START\n")
        h.append("; generated by plymeld $version\n")
        h.append("; total layer number: $layers\n")
        h.append("; filament_diameter: ${tools.joinToString(",") { n(diameterMm) }}\n")
        h.append("; max_z_height: ${n(maxZ)}\n")
        h.append("; filament: ${tools.indices.joinToString(",") { "${it + 1}" }}\n")
        h.append("; HEADER_BLOCK_END\n\n")
        h.append("; filament used [mm] = ${list(mm.map { f2(it) })}\n")
        h.append("; filament used [cm3] = ${list(mm.map { f2(it * area / 1000) })}\n")
        for ((i, t) in tools.withIndex()) {
            val attrs = buildList {
                add("id=\"${i + 1}\"")
                t.kind?.let { add("type=\"$it\"") }
                t.color?.let { add("color=\"$it\"") }
                add("used_m=\"${f2(mm[i] / 1000)}\"")
            }
            h.append("; <filament ${attrs.joinToString(" ")} />\n")
        }
        h.append("; total filament change = ${Predict.toolChanges(body)}\n")
        h.append("; total layers count = $layers\n")
        prediction.timeS?.let { h.append("; estimated printing time (normal mode) = ${hms(it)}\n") }
        prediction.layerS.firstOrNull()?.let { h.append("; estimated first layer printing time (normal mode) = ${hms(it)}\n") }
        h.append("\n")
        val rest = lines.dropWhile { it.startsWith("; generated by plymeld") || it.startsWith("; total layer number:") }
        return h.toString() + rest.joinToString("\n")
    }

    /**
     * Net filament (mm) pushed of each filament number (index 0 = filament 1): relative E (M83, as plymeld writes), the tool
     * from each T command, a tool's filament its own number until a `; FILAMENT_SWAP: T<t> filament <a> -> <b>` note
     * (KlipperWriter.FILAMENT_SWAP: swapped by hand at a pause) moves its lines to number b.
     */
    fun filamentByTool(text: String, tools: Int): DoubleArray {
        val out = DoubleArray(maxOf(tools, 1)); var tool = 0
        val filOf = HashMap<Int, Int>()
        for (line in text.lineSequence()) {
            if (line.startsWith("; FILAMENT_SWAP:")) {
                plymeld.gcode.KlipperWriter.FILAMENT_SWAP_LINE.find(line)?.let { filOf[it.groupValues[1].toInt()] = it.groupValues[3].toInt() - 1 }
                continue
            }
            val c = line.substringBefore(';').trim()
            if (c.length >= 2 && c[0] == 'T' && c.substring(1).all { it.isDigit() }) { tool = c.substring(1).toInt(); continue }
            if (!(c.startsWith("G1") || c.startsWith("G0") || c.startsWith("G2") || c.startsWith("G3"))) continue
            val v = c.split(' ').firstOrNull { it.startsWith("E") }?.substring(1)?.toDoubleOrNull() ?: continue
            val f = filOf[tool] ?: tool
            if (f in out.indices) out[f] += v
        }
        return out
    }

    /** Flash Studio's duration format: "18h 19m 58s", "6m 12s", "9s". */
    fun hms(s: Double): String {
        val t = Math.round(s); val hh = t / 3600; val mm = (t % 3600) / 60; val ss = t % 60
        return when { hh > 0 -> "${hh}h ${mm}m ${ss}s"; mm > 0 -> "${mm}m ${ss}s"; else -> "${ss}s" }
    }

    private fun f2(v: Double) = String.format(Locale.ROOT, "%.2f", v)
    private fun n(v: Double) = String.format(Locale.ROOT, "%.3f", v).trimEnd('0').trimEnd('.')
}
